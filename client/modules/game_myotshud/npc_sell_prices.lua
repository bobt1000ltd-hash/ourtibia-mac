function getOurNpcSellTooltip(itemId)
 local entry=OurNpcSellPrices[itemId]
 if not entry or not entry.offers or #entry.offers==0 then return nil end
 if not (ourDetailed and ourDetailed() or (not ourDetailed and g_keyboard.isShiftPressed())) then return nil end
 local best
 for _,offer in ipairs(entry.offers) do
  local price=tonumber(offer.price) or 0
  if price>0 and (not best or price>best.price or (price==best.price and offer.npc<best.npc)) then best={npc=offer.npc,price=price} end
 end
 return best and ("["..best.npc.."] – "..best.price.." gold") or nil
end

